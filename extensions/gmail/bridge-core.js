/*
 * OneKeel Gmail bridge: pure helpers shared by the content script, the options page and the unit
 * tests (features/embed/email/gmail-bridge.test.ts). No DOM and no chrome.* access in here.
 * Classic script (content scripts cannot be ES modules): publishes globalThis.OneKeelBridge.
 *
 * Protocol (window.postMessage between the Gmail tab and the Calendar popup):
 *   app -> Gmail  hello   {app, v, type:"hello",  nonce}
 *   Gmail -> app  ready   {app, v, type:"ready",  nonce}
 *   app -> Gmail  insert  {app, v, type:"insert", nonce, requestId, html, text}
 *   Gmail -> app  result  {app, v, type:"result", nonce, requestId, ok, reason?}
 * The nonce is generated by the extension per opened popup and handed over in the URL fragment
 * (never sent to the server). Only selected-times HTML/text ever travels. Keep constants in sync
 * with features/embed/email/gmail-bridge.ts (a unit test asserts they match).
 */
(function (root) {
  "use strict";

  var APP_ID = "onekeel-calendar";
  var VERSION = 1;
  var GMAIL_ORIGIN = "https://mail.google.com";
  var DEFAULT_APP_URL = "https://onekeel-calendar.onrender.com";
  var SCHEDULE_PATH = "/schedule";
  var NONCE_RE = /^[a-f0-9]{32}$/;
  var REQUEST_ID_RE = /^[A-Za-z0-9_-]{1,64}$/;
  var MAX_HTML = 100000;
  var MAX_TEXT = 20000;

  // ---------------------------------------------------------------- app URL

  /** Origin of a configured Calendar app URL, or null. https only; http only for localhost dev. */
  function normalizeAppUrl(input) {
    if (typeof input !== "string") return null;
    var url;
    try {
      url = new URL(input.trim());
    } catch (e) {
      return null;
    }
    if (url.username || url.password) return null;
    var local = url.hostname === "localhost" || url.hostname === "127.0.0.1" || url.hostname === "[::1]";
    if (url.protocol === "https:") return url.origin;
    if (url.protocol === "http:" && local) return url.origin;
    return null;
  }

  function scheduleUrl(appOrigin, nonce) {
    return appOrigin + SCHEDULE_PATH + "?gmail=1#nonce=" + nonce;
  }

  // ---------------------------------------------------------------- nonce

  function createNonce(cryptoObj) {
    var c = cryptoObj || root.crypto;
    if (!c || typeof c.getRandomValues !== "function") throw new Error("No secure random source");
    var bytes = new Uint8Array(16);
    c.getRandomValues(bytes);
    var out = "";
    for (var i = 0; i < bytes.length; i++) out += (bytes[i] < 16 ? "0" : "") + bytes[i].toString(16);
    return out;
  }

  function isNonce(value) {
    return typeof value === "string" && NONCE_RE.test(value);
  }

  function sameNonce(a, b) {
    if (!isNonce(a) || !isNonce(b)) return false;
    var diff = 0;
    for (var i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
    return diff === 0;
  }

  // ---------------------------------------------------------------- messages

  function isPlainObject(v) {
    return v !== null && typeof v === "object" && !Array.isArray(v);
  }

  /**
   * Checks a message received by Gmail: exact app origin, event.source is the popup this session
   * opened, shape, version and nonce. ctx = {appOrigin, popup, nonce}.
   */
  function validateAppMessage(event, ctx) {
    if (!event || !ctx || !ctx.appOrigin || !ctx.popup) return { ok: false, reason: "no-session" };
    if (event.origin !== ctx.appOrigin) return { ok: false, reason: "origin" };
    if (event.source !== ctx.popup) return { ok: false, reason: "source" };
    var d = event.data;
    if (!isPlainObject(d) || d.app !== APP_ID || d.v !== VERSION) return { ok: false, reason: "shape" };
    if (!sameNonce(d.nonce, ctx.nonce)) return { ok: false, reason: "nonce" };
    if (d.type === "hello") return { ok: true, message: { type: "hello" } };
    if (d.type === "insert") {
      if (typeof d.requestId !== "string" || !REQUEST_ID_RE.test(d.requestId)) return { ok: false, reason: "shape" };
      if (typeof d.html !== "string" || d.html.length === 0 || d.html.length > MAX_HTML) return { ok: false, reason: "size" };
      if (d.text !== undefined && (typeof d.text !== "string" || d.text.length > MAX_TEXT)) return { ok: false, reason: "size" };
      return { ok: true, message: { type: "insert", requestId: d.requestId, html: d.html, text: typeof d.text === "string" ? d.text : "" } };
    }
    return { ok: false, reason: "type" };
  }

  function buildReady(nonce) {
    return { app: APP_ID, v: VERSION, type: "ready", nonce: nonce };
  }

  function buildResult(nonce, requestId, ok, reason) {
    var m = { app: APP_ID, v: VERSION, type: "result", nonce: nonce, requestId: requestId, ok: !!ok };
    if (reason) m.reason = String(reason).slice(0, 40);
    return m;
  }

  // ---------------------------------------------------------------- sanitizer

  var ALLOWED_TAGS = {
    table: 1, thead: 1, tbody: 1, tfoot: 1, tr: 1, td: 1, th: 1, div: 1, p: 1, span: 1, br: 1, hr: 1,
    strong: 1, b: 1, em: 1, i: 1, u: 1, small: 1, a: 1, ul: 1, ol: 1, li: 1, h1: 1, h2: 1, h3: 1, h4: 1,
  };
  var VOID_TAGS = { br: 1, hr: 1 };
  // Tags whose whole content is dropped, not just the tag.
  var DROP_CONTENT = {
    script: 1, style: 1, iframe: 1, frame: 1, frameset: 1, object: 1, embed: 1, noscript: 1, template: 1,
    svg: 1, math: 1, title: 1, head: 1, textarea: 1, select: 1, applet: 1, xmp: 1, plaintext: 1,
  };
  var STYLE_PROPS = {
    color: 1, "background-color": 1, background: 1, "font-family": 1, "font-size": 1, "font-weight": 1,
    "font-style": 1, "line-height": 1, "letter-spacing": 1, "text-align": 1, "text-decoration": 1,
    "text-transform": 1, "vertical-align": 1, padding: 1, "padding-top": 1, "padding-right": 1,
    "padding-bottom": 1, "padding-left": 1, margin: 1, "margin-top": 1, "margin-right": 1,
    "margin-bottom": 1, "margin-left": 1, border: 1, "border-top": 1, "border-right": 1,
    "border-bottom": 1, "border-left": 1, "border-color": 1, "border-style": 1, "border-width": 1,
    "border-radius": 1, "border-collapse": 1, "border-spacing": 1, width: 1, "max-width": 1,
    "min-width": 1, height: 1, display: 1, "white-space": 1,
  };
  var DISPLAY_OK = { block: 1, "inline-block": 1, inline: 1, "table-cell": 1, none: 0 };
  var ENTITY_NAMED = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", colon: ":", tab: "\t", newline: "\n", nbsp: " ", sol: "/", lpar: "(", rpar: ")" };

  function escapeAttr(s) {
    return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#39;");
  }

  function decodeEntities(s) {
    return String(s).replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);?/gi, function (m, body) {
      var lower = body.toLowerCase();
      if (lower.charAt(0) === "#") {
        var code = lower.charAt(1) === "x" ? parseInt(lower.slice(2), 16) : parseInt(lower.slice(1), 10);
        if (!isFinite(code) || code <= 0 || code > 0x10ffff) return "";
        try {
          return String.fromCodePoint(code);
        } catch (e) {
          return "";
        }
      }
      return Object.prototype.hasOwnProperty.call(ENTITY_NAMED, lower) ? ENTITY_NAMED[lower] : m;
    });
  }

  function cleanText(text) {
    // Entities that are already well-formed stay; every bare & and every < > is escaped.
    return String(text)
      .replace(/&(?!(?:#\d{1,7}|#x[0-9a-f]{1,6}|[a-z][a-z0-9]{1,31});)/gi, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");
  }

  function safeHref(raw) {
    var v = decodeEntities(raw).replace(/[\u0000-\u0020\u007f-\u009f\u200b-\u200f\u2028\u2029\ufeff]/g, "");
    if (!v || v.length > 2048) return null;
    if (/^mailto:[^\s<>"']+$/i.test(v)) return v;
    if (!/^https?:\/\//i.test(v)) return null;
    try {
      var u = new URL(v);
      if ((u.protocol !== "https:" && u.protocol !== "http:") || u.username || u.password) return null;
    } catch (e) {
      return null;
    }
    return v;
  }

  function safeStyle(raw) {
    var v = decodeEntities(raw);
    if (/[\\<>]|\/\*|url\s*\(|expression|javascript|vbscript|@import|behavior|binding|var\s*\(|attr\s*\(/i.test(v)) return "";
    var out = [];
    var parts = v.split(";");
    for (var i = 0; i < parts.length; i++) {
      var idx = parts[i].indexOf(":");
      if (idx < 1) continue;
      var prop = parts[i].slice(0, idx).trim().toLowerCase();
      var val = parts[i].slice(idx + 1).trim();
      if (!Object.prototype.hasOwnProperty.call(STYLE_PROPS, prop) || !val || val.length > 300) continue;
      if (!/^[\w\s#%.,()'"!+-]+$/.test(val)) continue;
      if (prop === "display" && !DISPLAY_OK[val.toLowerCase()]) continue;
      out.push(prop + ":" + val);
    }
    return out.join(";");
  }

  var NUM_RE = /^\d{1,4}%?$/;
  var COLOR_RE = /^(#[0-9a-f]{3,8}|[a-z]{3,20})$/i;
  var ATTR_RULES = {
    align: /^(left|right|center|justify)$/i,
    valign: /^(top|middle|bottom|baseline)$/i,
    width: NUM_RE, height: NUM_RE, colspan: /^\d{1,2}$/, rowspan: /^\d{1,2}$/,
    cellpadding: /^\d{1,3}$/, cellspacing: /^\d{1,3}$/, border: /^\d{1,2}$/,
    bgcolor: COLOR_RE, role: /^presentation$/i,
  };

  function buildOpenTag(name, attrSrc) {
    var attrs = {};
    var re = /([^\s"'<>\/=`]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'=<>`]+)))?/g;
    var m;
    while ((m = re.exec(attrSrc))) {
      var key = m[1].toLowerCase();
      var val = m[2] !== undefined ? m[2] : m[3] !== undefined ? m[3] : m[4] !== undefined ? m[4] : "";
      if (Object.prototype.hasOwnProperty.call(attrs, key)) continue; // first wins, like browsers
      if (key === "style") {
        var s = safeStyle(val);
        if (s) attrs.style = s;
      } else if (key === "href" && name === "a") {
        var href = safeHref(val);
        if (href) attrs.href = href;
      } else if (Object.prototype.hasOwnProperty.call(ATTR_RULES, key)) {
        var plain = decodeEntities(val).trim();
        if (ATTR_RULES[key].test(plain)) attrs[key] = plain;
      }
    }
    if (name === "a") {
      if (!attrs.href) return null;
      attrs.target = "_blank";
      attrs.rel = "noopener noreferrer";
    }
    var out = "<" + name;
    for (var k in attrs) if (Object.prototype.hasOwnProperty.call(attrs, k)) out += " " + k + '="' + escapeAttr(attrs[k]) + '"';
    return out + ">";
  }

  /**
   * Rebuilds `html` from an allowlist (tables, text, links, inline styles) and drops everything
   * else: scripts, styles, frames, forms, images, event handlers, classes, ids, data-*, comments,
   * javascript:/data: links, url() and expression() styles. Returns "" when input is not a
   * string or is over MAX_HTML (rejected, not truncated, so markup is never cut mid-tag).
   */
  function sanitizeHtml(html) {
    if (typeof html !== "string" || html.length === 0 || html.length > MAX_HTML) return "";
    var out = "";
    var stack = [];
    var i = 0;
    var n = html.length;
    var skip = null;
    var TAG = /^<(\/?)([a-zA-Z][a-zA-Z0-9]*)((?:"[^"]*"|'[^']*'|[^'">])*)>?/;
    while (i < n) {
      var lt = html.indexOf("<", i);
      if (lt === -1) lt = n;
      if (lt > i && !skip) out += cleanText(html.slice(i, lt));
      if (lt >= n) break;
      i = lt;
      if (html.startsWith("<!--", i)) {
        var endC = html.indexOf("-->", i + 4);
        i = endC === -1 ? n : endC + 3;
        continue;
      }
      var m = TAG.exec(html.slice(i, i + 4000));
      if (!m) {
        // "<" that does not start a tag (or a declaration/PI): drop through the next ">".
        if (/^<[!?\/]/.test(html.slice(i, i + 2))) {
          var gt = html.indexOf(">", i);
          i = gt === -1 ? n : gt + 1;
        } else {
          if (!skip) out += "&lt;";
          i += 1;
        }
        continue;
      }
      i += m[0].length;
      var closing = m[1] === "/";
      var name = m[2].toLowerCase();
      if (skip) {
        if (closing && name === skip) skip = null;
        continue;
      }
      if (!closing && Object.prototype.hasOwnProperty.call(DROP_CONTENT, name)) {
        skip = name;
        continue;
      }
      if (!Object.prototype.hasOwnProperty.call(ALLOWED_TAGS, name)) continue; // tag dropped, text kept
      if (!closing) {
        var open = buildOpenTag(name, m[3] || "");
        if (Object.prototype.hasOwnProperty.call(VOID_TAGS, name)) {
          if (open) out += open;
        } else {
          stack.push({ name: name, emitted: open !== null });
          if (open) out += open;
        }
      } else if (!Object.prototype.hasOwnProperty.call(VOID_TAGS, name)) {
        var at = -1;
        for (var s = stack.length - 1; s >= 0; s--) {
          if (stack[s].name === name) {
            at = s;
            break;
          }
        }
        if (at === -1) continue; // stray close tag
        while (stack.length > at) {
          var top = stack.pop();
          if (top.emitted) out += "</" + top.name + ">";
        }
      }
    }
    while (stack.length) {
      var t = stack.pop();
      if (t.emitted) out += "</" + t.name + ">";
    }
    return out;
  }

  function sanitizeText(text) {
    if (typeof text !== "string") return "";
    return text.replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, "").replace(/\r\n?/g, "\n").slice(0, MAX_TEXT);
  }

  var api = {
    APP_ID: APP_ID, VERSION: VERSION, GMAIL_ORIGIN: GMAIL_ORIGIN, DEFAULT_APP_URL: DEFAULT_APP_URL,
    SCHEDULE_PATH: SCHEDULE_PATH, MAX_HTML: MAX_HTML, MAX_TEXT: MAX_TEXT,
    normalizeAppUrl: normalizeAppUrl, scheduleUrl: scheduleUrl, createNonce: createNonce, isNonce: isNonce,
    sameNonce: sameNonce, validateAppMessage: validateAppMessage, buildReady: buildReady, buildResult: buildResult,
    sanitizeHtml: sanitizeHtml, sanitizeText: sanitizeText,
  };
  root.OneKeelBridge = api;
})(typeof globalThis !== "undefined" ? globalThis : this);
